"""Rebuild every web asset in public/ from the Etonia app repository.

Usage:  python scripts/build_assets.py [path/to/Etonia]

Sources (newest designs):
  assets/icon/etonia.png                     app icon (lavender tile)
  Marketing/material/tonia_front.png         canonical Tonia, transparent
  assets/animations/etonia_loops/<name>/     12 fps Tonia loops (Nov 15 rig)
  assets/animations/etonia_thinking/<name>/  pen spin / walk loops
  docs/assets/screenshots/                   regenerated by tool/generate_screenshots_test.dart
  build/appstore_screenshots/iphone/         regenerated by the same test
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "Etonia"
PUB = ROOT / "public"
APP = ROOT / "app"

BG = (250, 249, 247)
INK = (52, 50, 57)
INK2 = (112, 109, 118)
BRAND = (119, 97, 165)
LILAC = (240, 235, 248)


def out(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


# ---------------------------------------------------------------- Tonia loops
LOOPS = {
    # name: (source dir, frame count, fps)
    "look_around": ("etonia_loops/look_around", 12, 12),
    "think": ("etonia_loops/think", 12, 12),
    "hop": ("etonia_loops/hop", 12, 12),
    "write": ("etonia_loops/write", 12, 12),
    "run": ("etonia_loops/run", 12, 12),
    "pop_out": ("etonia_loops/pop_out", 12, 12),
    "attend": ("etonia_loops/attend", 12, 12),
    "grade": ("etonia_loops/grade", 24, 12),
    "pen_spin": ("etonia_thinking/pen_spin", 24, 6),
    "walk": ("etonia_thinking/walk", 24, 12),
}
FRAME_W, FRAME_H = 300, 353  # 512x603 source, ~0.586 scale; crisp up to ~150 css px @2x


def build_loops() -> None:
    manifest = {"frame": [FRAME_W, FRAME_H], "loops": {}}
    for name, (rel, count, fps) in LOOPS.items():
        frames = sorted((SRC / "assets/animations" / rel).glob("*.png"))[:count]
        if len(frames) != count:
            raise SystemExit(f"{name}: expected {count} frames, found {len(frames)}")
        sheet = Image.new("RGBA", (FRAME_W * count, FRAME_H), (0, 0, 0, 0))
        for i, f in enumerate(frames):
            im = Image.open(f).convert("RGBA").resize((FRAME_W, FRAME_H), Image.LANCZOS)
            sheet.alpha_composite(im, (i * FRAME_W, 0))
        sheet.save(out(PUB / "tonia" / f"{name}.webp"), "WEBP", quality=82, method=6)
        manifest["loops"][name] = {"frames": count, "fps": fps}
        print("loop", name, count)
    (ROOT / "lib").mkdir(exist_ok=True)
    (ROOT / "lib" / "tonia-loops.json").write_text(json.dumps(manifest, indent=2) + "\n")


# ------------------------------------------------------------------ stills
def build_stills() -> None:
    tonia = Image.open(SRC / "Marketing/material/tonia_front.png").convert("RGBA")
    tonia = tonia.crop(tonia.getbbox())
    t = tonia.copy()
    t.thumbnail((640, 640), Image.LANCZOS)
    t.save(out(PUB / "tonia" / "tonia.webp"), "WEBP", quality=88, method=6)
    t.save(out(PUB / "tonia" / "tonia.png"), optimize=True)

    icon = Image.open(SRC / "assets/icon/etonia.png").convert("RGBA")
    icon.resize((512, 512), Image.LANCZOS).save(out(PUB / "brand" / "etonia-icon-512.png"), optimize=True)
    icon.resize((192, 192), Image.LANCZOS).save(out(PUB / "brand" / "etonia-icon-192.png"), optimize=True)
    icon.resize((256, 256), Image.LANCZOS).save(out(PUB / "brand" / "etonia-icon.webp"), "WEBP", quality=90)
    # Next.js app-router metadata files
    icon.resize((512, 512), Image.LANCZOS).save(out(APP / "icon.png"), optimize=True)
    icon.resize((180, 180), Image.LANCZOS).convert("RGB").save(out(APP / "apple-icon.png"), optimize=True)
    icon.save(out(APP / "favicon.ico"), sizes=[(16, 16), (32, 32), (48, 48)])
    return tonia


# --------------------------------------------------------------- screenshots
SHOTS = {
    "docs/assets/screenshots/ai_before.png": "ai-before",
    "docs/assets/screenshots/ai_after.png": "ai-after",
    "docs/assets/screenshots/ai_scroll_1.png": "ai-step-1",
    "docs/assets/screenshots/ai_scroll_2.png": "ai-step-2",
    "docs/assets/screenshots/ai_scroll_3.png": "ai-step-3",
    "docs/assets/screenshots/feature_ink_studio_light.png": "ink-studio",
    "docs/assets/screenshots/feature_library_light.png": "library",
    "build/appstore_screenshots/ipad/06_dark_mode_studio.png": "dark-studio",
}
PHONE = {
    "build/appstore_screenshots/iphone/01_ai_annotate_and_plot.png": "phone-ai",
    "build/appstore_screenshots/iphone/04_free_note_studio.png": "phone-studio",
    "build/appstore_screenshots/iphone/05_library_and_folders.png": "phone-library",
}


def build_screens() -> dict:
    sizes = {}
    for table, width in ((SHOTS, 1600), (PHONE, 640)):
        for rel, name in table.items():
            im = Image.open(SRC / rel).convert("RGB")
            h = round(im.height * width / im.width)
            im = im.resize((width, h), Image.LANCZOS)
            im.save(out(PUB / "screens" / f"{name}.webp"), "WEBP", quality=86, method=6)
            sizes[name] = [width, h]
            print("screen", name, width, h)
    (ROOT / "lib" / "screens.json").write_text(json.dumps(sizes, indent=2) + "\n")
    return sizes


# ------------------------------------------------------------------ OG card
def font(path: Path, size: int, weight: int | None = None):
    f = ImageFont.truetype(str(path), size)
    if weight is not None:
        try:
            axes = f.get_variation_axes()
            values = []
            for a in axes:
                tag = a.get("name", b"")
                tag = tag.decode() if isinstance(tag, bytes) else str(tag)
                if "eight" in tag:
                    values.append(weight)
                elif "ptical" in tag:
                    values.append(min(max(size, a["minimum"]), a["maximum"]))
                else:
                    values.append(a["default"])
            f.set_variation_by_axes(values)
        except Exception:
            pass
    return f


def build_og(tonia: Image.Image) -> None:
    W, H = 1200, 630
    og = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(og)
    # soft lilac blob behind Tonia
    d.ellipse((800, 90, 1220, 510), fill=LILAC)
    # ruled paper lines
    for y in range(120, H, 44):
        d.line((0, y, 700, y), fill=(236, 232, 238), width=1)
    d.line((92, 0, 92, H), fill=(240, 205, 214), width=2)

    t = tonia.copy()
    t.thumbnail((340, 410), Image.LANCZOS)
    og.paste(t, (840, 120), t)

    serif = ROOT / "app/fonts/Newsreader.ttf"
    sans = ROOT / "app/fonts/Inter.ttf"
    icon = Image.open(PUB / "brand/etonia-icon-192.png").convert("RGBA").resize((72, 72), Image.LANCZOS)
    mask = Image.new("L", (72, 72), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, 71, 71), 16, fill=255)
    og.paste(icon, (130, 92), mask)
    d.text((220, 106), "Etonia", font=font(sans, 40, 600), fill=INK)
    head = font(serif, 62, 500)
    d.text((130, 210), "Handwritten notes", font=head, fill=INK)
    d.text((130, 280), "that think with you.", font=head, fill=BRAND)
    body = font(sans, 28, 400)
    d.text((132, 412), "AI that plots on your page · a Study Desk tutor", font=body, fill=INK2)
    d.text((132, 452), "Every notebook feature free, no ads.", font=body, fill=INK2)
    d.text((132, 540), "etonia.io", font=font(sans, 26, 600), fill=BRAND)
    og.save(out(APP / "opengraph-image.png"), optimize=True)
    og.save(out(APP / "twitter-image.png"), optimize=True)


def main() -> None:
    if not SRC.exists():
        raise SystemExit(f"Etonia source repo not found at {SRC}")
    build_loops()
    tonia = build_stills()
    build_screens()
    build_og(tonia)
    print("done")


if __name__ == "__main__":
    main()
